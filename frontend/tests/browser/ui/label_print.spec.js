import { test, expect } from '@playwright/test';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const dist = fileURLToPath(new URL('../../../dist/', import.meta.url));

for (const language of ['en', 'id']) test(`print workspace distinguishes demo from operational output in ${language}`, async ({ page }, testInfo) => {
  const api = [];
  page.on('request', request => { if (request.url().includes('/api/')) api.push(request.url()); });
  await page.route('**/*', async route => {
    const url = new URL(route.request().url());
    if (url.pathname === '/api/v1/label-print/printers') return route.fulfill({ json: { policy_origin: 'management', printers: [] } });
    if (url.hostname !== '127.0.0.1') return route.abort();
    if (url.pathname === '/print') return route.fulfill({ path: path.join(dist, 'index.html'), contentType: 'text/html' });
    if (url.pathname.startsWith('/assets/')) {
      const file = path.resolve(dist, `.${decodeURIComponent(url.pathname)}`);
      if (file.startsWith(path.join(dist, 'assets') + path.sep)) return route.fulfill({ path: file });
    }
    return route.abort();
  });
  await page.addInitScript(lang => localStorage.setItem('thermal-label-studio.preferences.v1', JSON.stringify({ language: lang, theme: 'industrial-dark' })), language);
  await page.goto('/print');
  const id = language === 'id';
  const demo = page.getByRole('checkbox', { name: id ? 'Mode demonstrasi' : 'Demo mode', exact: true });
  const getData = page.getByRole('button', { name: id ? 'Ambil Data' : 'Get Data', exact: true });
  await expect(demo).not.toBeChecked();
  await expect(page.getByRole('button', { name: id ? 'Cetak' : 'Print', exact: true })).toBeDisabled();
  await page.getByRole('textbox', { name: id ? 'Batch baris 1' : 'Batch row 1', exact: true }).fill('0010245801');
  await page.getByRole('textbox', { name: id ? 'Batch baris 2' : 'Batch row 2', exact: true }).fill('0010245802');
  await getData.click(); await page.locator('#print-settings-tab-printer').click();
  await expect(page.locator('.label-print-gallery img')).toHaveCount(0);
  await demo.check(); await getData.click(); await page.locator('#print-settings-tab-printer').click();
  const cards = page.locator('.label-print-card');
  await expect(cards).toHaveCount(2);
  expect(await cards.locator('img').first().evaluate(image => image.complete && image.naturalWidth === 640)).toBe(true);
  await cards.first().locator('.label-print-thumbnail').click();
  await page.locator('#label-inspector-tab-detail').click();
  await expect(page.locator('#label-inspector-panel-detail')).toContainText('0010245801');
  await expect(page.locator('#label-inspector-panel-detail')).toContainText('SAMPLE_ROLL');
  await page.locator('#label-inspector-tab-preview').click();
  await cards.nth(1).locator('.label-print-thumbnail').click();
  await expect(page.locator('#label-inspector-panel-preview img')).toHaveAttribute('alt', /0010245802/);
  const copies = page.getByRole('spinbutton');
  await expect(copies).toHaveValue('1'); await copies.fill('3');
  const print = page.getByRole('button', { name: id ? 'Simulasikan cetak' : 'Simulate print', exact: true });
  await print.click();
  await expect(page.locator('.label-print-status')).toContainText(id ? '6 cetakan' : '6 prints');
  await cards.first().getByRole('checkbox').uncheck();
  await print.click();
  await expect(page.locator('.label-print-status')).toContainText(id ? '3 cetakan' : '3 prints');
  await copies.fill('1.5'); await expect(print).toBeDisabled();
  await copies.fill('1');
  await page.getByRole('button', { name: id ? 'Putuskan agent demo' : 'Disconnect demo agent' }).click();
  await expect(print).toBeDisabled();
  await page.getByRole('button', { name: id ? 'Hubungkan agent demo' : 'Connect demo agent' }).click();
  await expect(print).toBeEnabled();
  await page.getByLabel(id ? 'Sambungan printer' : 'Printer connection', { exact: true }).selectOption('USB');
  await expect(page.getByRole('table', { name: id ? 'Nomor batch' : 'Batch numbers' })).toBeVisible();
  await page.getByRole('button', { name: id ? 'Ringkas input' : 'Collapse input', exact: true }).click();
  await expect(page.locator('#label-print-input')).toBeHidden();
  await page.getByRole('button', { name: id ? 'Tampilkan tabel batch' : 'Show batch table', exact: true }).click();
  await page.getByRole('button', { name: id ? 'Pratinjau kecil' : 'Small previews', exact: true }).click();
  await expect(page.locator('.label-print-results')).toHaveClass(/gallery-size-small/);
  await page.getByRole('button', { name: id ? 'Pratinjau besar' : 'Large previews', exact: true }).click();
  await expect(page.locator('.label-print-results')).toHaveClass(/gallery-size-large/);
  await page.getByRole('button', { name: id ? 'Pratinjau sedang' : 'Medium previews', exact: true }).click();
  await page.locator('#label-inspector-tab-preview').focus();
  await page.locator('#label-inspector-tab-preview').press('ArrowRight');
  await expect(page.locator('#label-inspector-tab-data')).toBeFocused();
  await expect(page.locator('#label-inspector-panel-data')).toBeVisible();
  await page.locator('#label-inspector-tab-preview').click();
  for (const width of [320, 540, 736, 1024, 1440]) {
    await page.setViewportSize({ width, height: 1100 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  }
  const inputBounds = await page.locator('.label-print-intake').boundingBox();
  const resultBounds = await page.locator('.label-print-results').boundingBox();
  const rightBounds = await page.locator('.label-print-right').boundingBox();
  expect(inputBounds.width).toBeLessThanOrEqual(200);
  expect(inputBounds.x + inputBounds.width).toBeLessThanOrEqual(resultBounds.x);
  expect(resultBounds.x + resultBounds.width).toBeLessThanOrEqual(rightBounds.x);
  await expect(page.locator('.label-print-message')).toBeVisible();
  await page.locator('.application-page').evaluate(element => { element.scrollTop = 0; });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath(`label-print-${language}.png`), fullPage: true });
  await page.getByLabel(id ? 'Bahasa printer' : 'Printer language', { exact: true }).selectOption('ZPL');
  await expect(cards).toHaveCount(0); await expect(print).toBeDisabled();
  await getData.click(); await page.locator('#print-settings-tab-printer').click();
  await page.getByRole('textbox', { name: id ? 'Batch baris 1' : 'Batch row 1', exact: true }).fill('0000000099');
  await expect(cards).toHaveCount(0);
  await getData.click(); await page.locator('#print-settings-tab-printer').click(); await demo.uncheck(); await expect(cards).toHaveCount(0);
  await expect(page.getByRole('button', { name: id ? 'Cetak' : 'Print', exact: true })).toBeDisabled();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(api.every(url => url.endsWith('/label-print/printers'))).toBe(true);
});
